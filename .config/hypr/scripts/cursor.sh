#!/usr/bin/env bash
# ===========================================================================
#  Monochrome Cursor Design Studio (cursor.sh)
#
#  Manages the 4 bespoke architectural cursor suites (hyprcursor + Xcursor),
#  live pointer sizing, GTK3/4 + Qt/X11 + GSettings synchronization, and
#  Kitty terminal cursor shape & 1ms GPU cursor trail.
#
#    cursor.sh                     interactive Rofi Cursor Design Studio
#    cursor.sh menu                interactive Rofi Cursor Design Studio
#    cursor.sh status [--json]     print active cursor theme, size & terminal cursor
#    cursor.sh ensure [--quiet]    build/install the 4 monochrome cursor suites
#    cursor.sh theme <name>        apply obsidian | ivory | precision | dot | <theme>
#    cursor.sh cycle               cycle Obsidian -> Ivory -> Precision -> Dot
#    cursor.sh size <px>           set cursor size (20 | 24 | 28 | 32 | 40 | 48)
#    cursor.sh kitty <shape>       set terminal cursor (block | beam | underline)
#    cursor.sh trail <on|off|toggle> toggle Kitty 1ms GPU cursor trail
#    cursor.sh hide-typing <on|off|toggle> toggle hide pointer while typing
# ===========================================================================

set -u
. "$(dirname "$0")/lib.sh"

case "${1:-}" in --*) set -- "${1#--}" "${@:2}" ;; esac

CURSOR_STATE="$CACHE_DIR/cursor.state"
ICONS_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/icons"
CURSOR_LUA="$HYPR_DIR/modules/cursor-user.lua"
KITTY_USER_CONF="$CONFIG_DIR/kitty/cursor-user.conf"

normalize_theme() {
    case "${1,,}" in
        obsidian|monochrome-obsidian|dark)      printf 'Monochrome-Obsidian' ;;
        ivory|monochrome-ivory|light|white)     printf 'Monochrome-Ivory' ;;
        precision|monochrome-precision|reticle) printf 'Monochrome-Precision' ;;
        dot|monochrome-dot|circle|minimal)      printf 'Monochrome-Dot' ;;
        *)                                      printf '%s' "$1" ;;
    esac
}

load_state() {
    CUR_THEME="$(mono_var cursor_theme "Monochrome-Obsidian")"
    CUR_SIZE="$(mono_var cursor_size "24")"
    CUR_KITTY="block"
    CUR_TRAIL="on"
    CUR_HIDE="off"
    [ "$(mono_var hide_cursor_typing "false")" = "true" ] && CUR_HIDE="on"

    if [ -r "$CURSOR_STATE" ]; then
        local k v
        while IFS='=' read -r k v; do
            case "$k" in
                theme) [ -n "$v" ] && CUR_THEME="$v" ;;
                size)  [ -n "$v" ] && CUR_SIZE="$v" ;;
                kitty) [ -n "$v" ] && CUR_KITTY="$v" ;;
                trail) [ -n "$v" ] && CUR_TRAIL="$v" ;;
                hide)  [ -n "$v" ] && CUR_HIDE="$v" ;;
            esac
        done < "$CURSOR_STATE"
    fi
}

save_state() {
    mkdir -p "$CACHE_DIR" 2>/dev/null || true
    cat > "$CURSOR_STATE" <<EOF
theme=$CUR_THEME
size=$CUR_SIZE
kitty=$CUR_KITTY
trail=$CUR_TRAIL
hide=$CUR_HIDE
EOF
}

write_lua_override() {
    mkdir -p "$(dirname "$CURSOR_LUA")" 2>/dev/null || true
    local hide_bool="false"
    [ "$CUR_HIDE" = "on" ] && hide_bool="true"
    cat > "$CURSOR_LUA" <<EOF
-- Auto-generated by cursor.sh (Cursor Design Studio)
hl.env("XCURSOR_THEME", "${CUR_THEME}")
hl.env("HYPRCURSOR_THEME", "${CUR_THEME}")
hl.env("XCURSOR_SIZE", "${CUR_SIZE}")
hl.env("HYPRCURSOR_SIZE", "${CUR_SIZE}")
hl.config({
    cursor = {
        enable_hyprcursor = true,
        hide_on_key_press = ${hide_bool},
    },
})
EOF
}

update_ini_key() { # update_ini_key <file> <key> <value>
    local file="$1" key="$2" val="$3"
    [ -f "$file" ] || return 0
    if grep -q "^${key}[[:space:]]*=" "$file" 2>/dev/null; then
        sed -i -E "s|^(${key}[[:space:]]*=[[:space:]]*).*|\1${val}|" "$file" 2>/dev/null || true
    else
        printf '%s = %s\n' "$key" "$val" >> "$file"
    fi
}

sync_toolkits() {
    update_ini_key "$CONFIG_DIR/gtk-3.0/settings.ini" "gtk-cursor-theme-name" "$CUR_THEME"
    update_ini_key "$CONFIG_DIR/gtk-3.0/settings.ini" "gtk-cursor-theme-size" "$CUR_SIZE"
    update_ini_key "$CONFIG_DIR/gtk-4.0/settings.ini" "gtk-cursor-theme-name" "$CUR_THEME"
    update_ini_key "$CONFIG_DIR/gtk-4.0/settings.ini" "gtk-cursor-theme-size" "$CUR_SIZE"

    local def_dir
    for def_dir in "$ICONS_DIR/default" "$HOME/.icons/default"; do
        mkdir -p "$def_dir" 2>/dev/null || true
        cat > "$def_dir/index.theme" <<EOF
[Icon Theme]
Name=Default
Comment=Default Monochrome Cursor Theme
Inherits=${CUR_THEME}
EOF
    done

    if have gsettings; then
        gsettings set org.gnome.desktop.interface cursor-theme "$CUR_THEME" >/dev/null 2>&1 || true
        gsettings set org.gnome.desktop.interface cursor-size "$CUR_SIZE" >/dev/null 2>&1 || true
    fi

    if have hyprctl; then
        hyprctl setcursor "$CUR_THEME" "$CUR_SIZE" >/dev/null 2>&1 || true
        hyprctl keyword env "XCURSOR_THEME,$CUR_THEME" >/dev/null 2>&1 || true
        hyprctl keyword env "HYPRCURSOR_THEME,$CUR_THEME" >/dev/null 2>&1 || true
        hyprctl keyword env "XCURSOR_SIZE,$CUR_SIZE" >/dev/null 2>&1 || true
        hyprctl keyword env "HYPRCURSOR_SIZE,$CUR_SIZE" >/dev/null 2>&1 || true
        local hide_bool="false"
        [ "$CUR_HIDE" = "on" ] && hide_bool="true"
        hyprctl keyword cursor:hide_on_key_press "$hide_bool" >/dev/null 2>&1 || true
    fi
}

write_kitty_cursor() {
    mkdir -p "$(dirname "$KITTY_USER_CONF")" 2>/dev/null || true
    local trail_val="1"
    [ "$CUR_TRAIL" = "off" ] && trail_val="0"
    cat > "$KITTY_USER_CONF" <<EOF
# Auto-generated by cursor.sh (Terminal Cursor Look)
cursor_shape                 ${CUR_KITTY}
cursor_trail                 ${trail_val}
cursor_trail_decay           0.09 0.32
cursor_trail_start_threshold 2
EOF
    if have pkill; then
        pkill -USR1 -x kitty >/dev/null 2>&1 || true
    fi
}

resolve_cursor_gen() {
    local cand
    for cand in \
        "$HYPR_DIR/bin/mono-cursor-gen" \
        "$SCRIPTS_DIR/../../../bin/cursor-gen" \
        "$CACHE_DIR/mono-cursor-gen"
    do
        [ -x "$cand" ] && { printf '%s\n' "$cand"; return 0; }
    done

    local src="$HYPR_DIR/src/mono-cursor-gen.c"
    if [ -f "$src" ]; then
        local cc_bin=""
        if have cc; then cc_bin="cc"
        elif have gcc; then cc_bin="gcc"
        elif have clang; then cc_bin="clang"
        fi
        if [ -n "$cc_bin" ]; then
            mkdir -p "$CACHE_DIR"
            if "$cc_bin" -std=c11 -O2 "$src" -o "$CACHE_DIR/mono-cursor-gen" -lm 2>/dev/null; then
                printf '%s\n' "$CACHE_DIR/mono-cursor-gen"
                return 0
            fi
        fi
    fi
    return 1
}

ensure_themes() {
    local quiet="${1:-}"
    mkdir -p "$ICONS_DIR" 2>/dev/null || true

    if [ -f "$ICONS_DIR/Monochrome-Obsidian/manifest.hl" ] && \
       [ -f "$ICONS_DIR/Monochrome-Ivory/manifest.hl" ] && \
       [ -f "$ICONS_DIR/Monochrome-Precision/manifest.hl" ] && \
       [ -f "$ICONS_DIR/Monochrome-Dot/manifest.hl" ]; then
        [ "$quiet" = "--quiet" ] || printf 'monochrome cursor suites ready in %s\n' "$ICONS_DIR"
        return 0
    fi

    local repo_cursors="$SCRIPTS_DIR/../../../cursors"
    if [ -d "$repo_cursors/Monochrome-Obsidian" ]; then
        cp -a "$repo_cursors"/Monochrome-* "$ICONS_DIR"/ 2>/dev/null || true
        [ "$quiet" = "--quiet" ] || printf 'installed prebuilt monochrome cursor suites to %s\n' "$ICONS_DIR"
        return 0
    fi

    local gen_bin
    if gen_bin="$(resolve_cursor_gen)"; then
        "$gen_bin" --out-dir "$ICONS_DIR" >/dev/null 2>&1 || return 1
        [ "$quiet" = "--quiet" ] || printf 'compiled 4 monochrome cursor suites in %s\n' "$ICONS_DIR"
        return 0
    fi
    return 1
}

cmd_status() {
    load_state
    if [ "${1:-}" = "--json" ]; then
        printf '{"theme":"%s","size":%s,"kitty":"%s","trail":"%s","hide_typing":"%s"}\n' \
            "$CUR_THEME" "$CUR_SIZE" "$CUR_KITTY" "$CUR_TRAIL" "$CUR_HIDE"
    else
        printf 'theme=%s size=%s kitty=%s trail=%s hide=%s\n' \
            "$CUR_THEME" "$CUR_SIZE" "$CUR_KITTY" "$CUR_TRAIL" "$CUR_HIDE"
    fi
}

cmd_theme() {
    local raw="${1:-}"
    [ -n "$raw" ] || { echo "usage: cursor.sh theme <obsidian|ivory|precision|dot|name>" >&2; exit 1; }
    load_state
    CUR_THEME="$(normalize_theme "$raw")"
    ensure_themes --quiet || true
    save_state
    write_lua_override
    sync_toolkits
    notify "Cursor Design" "${CUR_THEME} (${CUR_SIZE}px)"
}

cmd_cycle() {
    load_state
    case "$CUR_THEME" in
        Monochrome-Obsidian)  CUR_THEME="Monochrome-Ivory" ;;
        Monochrome-Ivory)     CUR_THEME="Monochrome-Precision" ;;
        Monochrome-Precision) CUR_THEME="Monochrome-Dot" ;;
        *)                    CUR_THEME="Monochrome-Obsidian" ;;
    esac
    ensure_themes --quiet || true
    save_state
    write_lua_override
    sync_toolkits
    notify "Cursor Design" "Switched to ${CUR_THEME} (${CUR_SIZE}px)"
}

cmd_size() {
    local sz="${1:-}"
    case "$sz" in
        16|20|24|28|32|36|40|48|64) ;;
        *) echo "cursor.sh: expected pixel size (e.g. 20, 24, 28, 32, 48)" >&2; exit 1 ;;
    esac
    load_state
    CUR_SIZE="$sz"
    save_state
    write_lua_override
    sync_toolkits
    notify "Cursor Size" "${CUR_THEME} @ ${CUR_SIZE}px"
}

cmd_kitty() {
    local sh="${1:-}"
    case "$sh" in
        block|beam|underline) ;;
        *) echo "cursor.sh: expected block | beam | underline" >&2; exit 1 ;;
    esac
    load_state
    CUR_KITTY="$sh"
    save_state
    write_kitty_cursor
    notify "Terminal Cursor" "Kitty cursor set to ${CUR_KITTY} (trail: ${CUR_TRAIL})"
}

cmd_trail() {
    local mode="${1:-toggle}"
    load_state
    case "$mode" in
        on|1|true)   CUR_TRAIL="on" ;;
        off|0|false) CUR_TRAIL="off" ;;
        toggle)      [ "$CUR_TRAIL" = "on" ] && CUR_TRAIL="off" || CUR_TRAIL="on" ;;
        *) echo "cursor.sh: expected on | off | toggle" >&2; exit 1 ;;
    esac
    save_state
    write_kitty_cursor
    notify "Terminal Cursor Trail" "1ms GPU cursor trail: ${CUR_TRAIL}"
}

cmd_hide_typing() {
    local mode="${1:-toggle}"
    load_state
    case "$mode" in
        on|1|true)   CUR_HIDE="on" ;;
        off|0|false) CUR_HIDE="off" ;;
        toggle)      [ "$CUR_HIDE" = "on" ] && CUR_HIDE="off" || CUR_HIDE="on" ;;
        *) echo "cursor.sh: expected on | off | toggle" >&2; exit 1 ;;
    esac
    save_state
    write_lua_override
    sync_toolkits
    notify "Cursor Auto-Hide" "Hide pointer while typing: ${CUR_HIDE}"
}

cmd_menu() {
    have rofi || exit 1
    load_state
    local tab=$'\t' choice key
    choice="$(printf '%s\n' \
        "theme:obsidian${tab}Pointer Design : Monochrome-Obsidian (Dark body, crisp silver edge)" \
        "theme:ivory${tab}Pointer Design : Monochrome-Ivory (Pure white body, dark edge)" \
        "theme:precision${tab}Pointer Design : Monochrome-Precision (Hollow CAD drafting reticle)" \
        "theme:dot${tab}Pointer Design : Monochrome-Dot (Minimalist halo & core dot)" \
        "size:20${tab}Pointer Size   : Compact (20px)" \
        "size:24${tab}Pointer Size   : Standard Desktop (24px)" \
        "size:32${tab}Pointer Size   : Large / HiDPI (32px)" \
        "size:48${tab}Pointer Size   : Studio / Presentation (48px)" \
        "kitty:block${tab}Terminal Look  : Solid Block Cursor" \
        "kitty:beam${tab}Terminal Look  : Vertical I-Beam Cursor" \
        "kitty:underline${tab}Terminal Look  : Minimal Underline Cursor" \
        "trail:toggle${tab}Terminal Trail : Toggle 1ms GPU Cursor Trail (now: ${CUR_TRAIL})" \
        "hide:toggle${tab}Typing Focus   : Toggle Hide Pointer While Typing (now: ${CUR_HIDE})" \
        | rofi_menu settings -dmenu -i -display-columns 2 -display-column-separator "$tab" \
            -p "cursor studio:" \
            -mesg "Active: ${CUR_THEME} (${CUR_SIZE}px) | Kitty: ${CUR_KITTY} (trail=${CUR_TRAIL})")" || exit 0
    [ -n "$choice" ] || exit 0
    key="${choice%%"$tab"*}"
    case "$key" in
        theme:*) cmd_theme "${key#theme:}" ;;
        size:*)  cmd_size "${key#size:}" ;;
        kitty:*) cmd_kitty "${key#kitty:}" ;;
        trail:*) cmd_trail "${key#trail:}" ;;
        hide:*)  cmd_hide_typing "${key#hide:}" ;;
    esac
}

case "${1:-menu}" in
    status)      cmd_status "${2:-}" ;;
    ensure|sync) ensure_themes "${2:-}" ;;
    theme|set)   cmd_theme "${2:-}" ;;
    cycle|next)  cmd_cycle ;;
    size)        cmd_size "${2:-}" ;;
    kitty)       cmd_kitty "${2:-}" ;;
    trail)       cmd_trail "${2:-toggle}" ;;
    hide-typing) cmd_hide_typing "${2:-toggle}" ;;
    menu|"")     cmd_menu ;;
    *)
        echo "usage: cursor.sh [menu|status|ensure|theme|cycle|size|kitty|trail|hide-typing]" >&2
        exit 1 ;;
esac
