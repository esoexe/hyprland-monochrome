#!/usr/bin/env bash
# ===========================================================================
#  Keyboard Type, Layout & Repeat Studio (keyboard.sh)
#
#  Configures physical keyboard hardware types (ANSI, ISO, 60%/HHKB, Vim
#  Caps-Escape, Emacs Control, Apple Cmd-Swap, Laptop), ergonomic &
#  international XKB keymaps (QWERTY, Colemak, Colemak-DH, Dvorak, Workman,
#  AZERTY, QWERTZ, multi-layout sets), and repeat physics in real time.
#
#    keyboard.sh                     interactive Rofi Keyboard Studio
#    keyboard.sh menu                interactive Rofi Keyboard Studio
#    keyboard.sh next                switch to next configured keyboard layout
#    keyboard.sh type <preset>       ansi | iso | compact60 | vim | emacs | apple | laptop
#    keyboard.sh layout <preset|xkb> qwerty | colemak | colemak-dh | dvorak | workman |
#                                    intl | azerty | qwertz | uk | us-ara | us-fr |
#                                    us-de | us-es | us-ru | <layout[:variant]>
#    keyboard.sh rate <preset>       tactile (38/260) | rapid (55/190) | gentle (25/360)
#    keyboard.sh status [--json|--waybar]
# ===========================================================================

set -u
. "$(dirname "$0")/lib.sh"

case "${1:-}" in --*) set -- "${1#--}" "${@:2}" ;; esac

KB_STATE="$CACHE_DIR/keyboard.state"
KB_LUA="$HYPR_DIR/modules/keyboard-user.lua"

load_kb_state() {
    KB_TYPE="ansi"
    KB_MODEL="$(mono_var kb_model "pc104")"
    KB_LAYOUT="$(mono_var kb_layout "us")"
    KB_VARIANT="$(mono_var kb_variant "")"
    KB_TYPE_OPTS=""
    KB_GRP_OPT=""
    KB_RATE_NAME="tactile"
    KB_REPEAT_RATE="$(mono_var repeat_rate "38")"
    KB_REPEAT_DELAY="$(mono_var repeat_delay "260")"
    KB_ACTIVE_IDX="0"

    local init_opts
    init_opts="$(mono_var kb_options "")"
    [ -n "$init_opts" ] && KB_TYPE_OPTS="$init_opts"

    if [ -r "$KB_STATE" ]; then
        local k v
        while IFS='=' read -r k v; do
            case "$k" in
                type)       [ -n "$v" ] && KB_TYPE="$v" ;;
                model)      KB_MODEL="$v" ;;
                layout)     [ -n "$v" ] && KB_LAYOUT="$v" ;;
                variant)    KB_VARIANT="$v" ;;
                type_opts)  KB_TYPE_OPTS="$v" ;;
                grp_opt)    KB_GRP_OPT="$v" ;;
                rate_name)  [ -n "$v" ] && KB_RATE_NAME="$v" ;;
                rate_hz)    [ -n "$v" ] && KB_REPEAT_RATE="$v" ;;
                rate_delay) [ -n "$v" ] && KB_REPEAT_DELAY="$v" ;;
                active_idx) [ -n "$v" ] && KB_ACTIVE_IDX="$v" ;;
            esac
        done < "$KB_STATE"
    fi
}

combined_options() {
    if [ -n "$KB_TYPE_OPTS" ] && [ -n "$KB_GRP_OPT" ]; then
        printf '%s,%s' "$KB_TYPE_OPTS" "$KB_GRP_OPT"
    elif [ -n "$KB_TYPE_OPTS" ]; then
        printf '%s' "$KB_TYPE_OPTS"
    else
        printf '%s' "$KB_GRP_OPT"
    fi
}

save_kb_state() {
    mkdir -p "$CACHE_DIR" 2>/dev/null || true
    cat > "$KB_STATE" <<EOF
type=$KB_TYPE
model=$KB_MODEL
layout=$KB_LAYOUT
variant=$KB_VARIANT
type_opts=$KB_TYPE_OPTS
grp_opt=$KB_GRP_OPT
rate_name=$KB_RATE_NAME
rate_hz=$KB_REPEAT_RATE
rate_delay=$KB_REPEAT_DELAY
active_idx=$KB_ACTIVE_IDX
EOF
}

write_kb_lua() {
    mkdir -p "$(dirname "$KB_LUA")" 2>/dev/null || true
    local opts
    opts="$(combined_options)"
    cat > "$KB_LUA" <<EOF
-- Auto-generated by keyboard.sh (Keyboard Type & Layout Studio)
hl.config({
    input = {
        kb_model     = "${KB_MODEL}",
        kb_layout    = "${KB_LAYOUT}",
        kb_variant   = "${KB_VARIANT}",
        kb_options   = "${opts}",
        repeat_rate  = ${KB_REPEAT_RATE},
        repeat_delay = ${KB_REPEAT_DELAY},
    },
})
EOF
}

signal_waybar() {
    if have pkill; then
        pkill -RTMIN+12 waybar >/dev/null 2>&1 || true
    fi
}

apply_live() {
    local opts
    opts="$(combined_options)"
    if have hyprctl; then
        hyprctl keyword input:kb_model "$KB_MODEL" >/dev/null 2>&1 || true
        hyprctl keyword input:kb_layout "$KB_LAYOUT" >/dev/null 2>&1 || true
        hyprctl keyword input:kb_variant "$KB_VARIANT" >/dev/null 2>&1 || true
        hyprctl keyword input:kb_options "$opts" >/dev/null 2>&1 || true
        hyprctl keyword input:repeat_rate "$KB_REPEAT_RATE" >/dev/null 2>&1 || true
        hyprctl keyword input:repeat_delay "$KB_REPEAT_DELAY" >/dev/null 2>&1 || true
    fi
    save_kb_state
    write_kb_lua
    signal_waybar
}

compute_badge() {
    local layouts_arr=() variants_arr=()
    IFS=',' read -r -a layouts_arr <<< "$KB_LAYOUT"
    IFS=',' read -r -a variants_arr <<< "$KB_VARIANT"
    local total="${#layouts_arr[@]}"
    [ "$total" -lt 1 ] && total=1
    local idx="${KB_ACTIVE_IDX:-0}"
    if [ "$idx" -ge "$total" ] || [ "$idx" -lt 0 ]; then idx=0; fi

    local active_l="${layouts_arr[$idx]:-us}"
    local active_v="${variants_arr[$idx]:-}"

    case "${active_l}:${active_v}" in
        us:colemak_dh) printf 'CMK-DH' ;;
        us:colemak)    printf 'CMK' ;;
        us:dvorak)     printf 'DVK' ;;
        us:workman)    printf 'WRK' ;;
        us:intl)       printf 'US-INT' ;;
        *)             printf '%s' "${active_l^^}" ;;
    esac
}

type_label() {
    case "$1" in
        ansi)      printf 'Standard ANSI 104-Key' ;;
        iso)       printf 'ISO 105-Key European/UK' ;;
        compact60) printf '60%% / HHKB Compact (Caps=Esc)' ;;
        vim)       printf 'Vim Ergonomic (Swap Caps/Esc)' ;;
        emacs)     printf 'Control Home-Row (Caps=Ctrl)' ;;
        apple)     printf 'Apple / Mac (Cmd=Super)' ;;
        laptop)    printf 'ThinkPad / Compact Laptop' ;;
        *)         printf '%s' "$1" ;;
    esac
}

cmd_type() {
    local preset="${1:-}"
    load_kb_state
    case "${preset,,}" in
        ansi|pc104|standard)
            KB_TYPE="ansi"; KB_MODEL="pc104"; KB_TYPE_OPTS="" ;;
        iso|pc105)
            KB_TYPE="iso"; KB_MODEL="pc105"; KB_TYPE_OPTS="" ;;
        compact60|60|hhkb)
            KB_TYPE="compact60"; KB_MODEL="pc104"; KB_TYPE_OPTS="caps:escape" ;;
        vim|ergo)
            KB_TYPE="vim"; KB_MODEL="pc104"; KB_TYPE_OPTS="caps:swapescape,shift:both_capslock" ;;
        emacs|unix|nocaps)
            KB_TYPE="emacs"; KB_MODEL="pc104"; KB_TYPE_OPTS="ctrl:nocaps" ;;
        apple|mac)
            KB_TYPE="apple"; KB_MODEL="applealu_ansi"; KB_TYPE_OPTS="altwin:swap_lalt_lwin" ;;
        laptop|thinkpad)
            KB_TYPE="laptop"; KB_MODEL="thinkpad60"; KB_TYPE_OPTS="" ;;
        *)
            echo "keyboard.sh: unknown type '$preset' (ansi|iso|compact60|vim|emacs|apple|laptop)" >&2
            exit 1 ;;
    esac
    apply_live
    notify "Keyboard Type" "$(type_label "$KB_TYPE")"
}

cmd_layout() {
    local spec="${1:-}"
    [ -n "$spec" ] || { echo "usage: keyboard.sh layout <preset|layout[:variant]>" >&2; exit 1; }
    load_kb_state
    KB_ACTIVE_IDX="0"

    case "${spec,,}" in
        qwerty|us)       KB_LAYOUT="us";     KB_VARIANT="";           KB_GRP_OPT="" ;;
        colemak)         KB_LAYOUT="us";     KB_VARIANT="colemak";    KB_GRP_OPT="" ;;
        colemak-dh|dh)   KB_LAYOUT="us";     KB_VARIANT="colemak_dh"; KB_GRP_OPT="" ;;
        dvorak)          KB_LAYOUT="us";     KB_VARIANT="dvorak";     KB_GRP_OPT="" ;;
        workman)         KB_LAYOUT="us";     KB_VARIANT="workman";    KB_GRP_OPT="" ;;
        intl|us-intl)    KB_LAYOUT="us";     KB_VARIANT="intl";       KB_GRP_OPT="" ;;
        azerty|fr)       KB_LAYOUT="fr";     KB_VARIANT="";           KB_GRP_OPT="" ;;
        qwertz|de)       KB_LAYOUT="de";     KB_VARIANT="";           KB_GRP_OPT="" ;;
        uk|gb)           KB_LAYOUT="gb";     KB_VARIANT="";           KB_GRP_OPT="" ;;
        arabic|us-ara)   KB_LAYOUT="us,ara"; KB_VARIANT="";           KB_GRP_OPT="grp:alt_shift_toggle" ;;
        us-fr)           KB_LAYOUT="us,fr";  KB_VARIANT="";           KB_GRP_OPT="grp:alt_shift_toggle" ;;
        us-de)           KB_LAYOUT="us,de";  KB_VARIANT="";           KB_GRP_OPT="grp:alt_shift_toggle" ;;
        us-es)           KB_LAYOUT="us,es";  KB_VARIANT="";           KB_GRP_OPT="grp:alt_shift_toggle" ;;
        us-ru)           KB_LAYOUT="us,ru";  KB_VARIANT="";           KB_GRP_OPT="grp:alt_shift_toggle" ;;
        *:*)
            KB_LAYOUT="${spec%%:*}"
            KB_VARIANT="${spec#*:}"
            case "$KB_LAYOUT" in *,*) KB_GRP_OPT="grp:alt_shift_toggle" ;; *) KB_GRP_OPT="" ;; esac
            ;;
        *)
            KB_LAYOUT="$spec"
            KB_VARIANT=""
            case "$KB_LAYOUT" in *,*) KB_GRP_OPT="grp:alt_shift_toggle" ;; *) KB_GRP_OPT="" ;; esac
            ;;
    esac

    apply_live
    local badge
    badge="$(compute_badge)"
    notify "Keyboard Layout" "${badge} (${KB_LAYOUT}${KB_VARIANT:+ / $KB_VARIANT})"
}

cmd_rate() {
    local preset="${1:-}"
    load_kb_state
    case "${preset,,}" in
        tactile|default|standard)
            KB_RATE_NAME="tactile"; KB_REPEAT_RATE="38"; KB_REPEAT_DELAY="260" ;;
        rapid|fast|turbo)
            KB_RATE_NAME="rapid";   KB_REPEAT_RATE="55"; KB_REPEAT_DELAY="190" ;;
        gentle|relaxed|slow)
            KB_RATE_NAME="gentle";  KB_REPEAT_RATE="25"; KB_REPEAT_DELAY="360" ;;
        *)
            echo "keyboard.sh: expected tactile | rapid | gentle" >&2
            exit 1 ;;
    esac
    apply_live
    notify "Key Repeat Physics" "${KB_RATE_NAME^} (${KB_REPEAT_RATE} Hz / ${KB_REPEAT_DELAY} ms delay)"
}

cmd_next() {
    load_kb_state
    local layouts_arr=()
    IFS=',' read -r -a layouts_arr <<< "$KB_LAYOUT"
    local total="${#layouts_arr[@]}"

    if have hyprctl; then
        hyprctl switchxkblayout all next >/dev/null 2>&1 \
            || hyprctl switchxkblayout current next >/dev/null 2>&1 || true
    fi

    if [ "$total" -gt 1 ]; then
        KB_ACTIVE_IDX=$(( (KB_ACTIVE_IDX + 1) % total ))
        save_kb_state
        signal_waybar
        notify "Keyboard Layout" "Active: $(compute_badge) (of ${KB_LAYOUT})"
    else
        # Single XKB layout configured: cycle core ergonomic variants cleanly
        case "${KB_LAYOUT}:${KB_VARIANT}" in
            us:)            cmd_layout "colemak-dh" ;;
            us:colemak_dh)  cmd_layout "dvorak" ;;
            us:dvorak)      cmd_layout "qwerty" ;;
            *)              notify "Keyboard Layout" "Active: $(compute_badge) (Super+Shift+X for Keyboard Studio)" ;;
        esac
    fi
}

cmd_status() {
    load_kb_state
    local badge opts tlabel
    badge="$(compute_badge)"
    opts="$(combined_options)"
    tlabel="$(type_label "$KB_TYPE")"

    case "${1:-}" in
        --json)
            printf '{"type":"%s","model":"%s","layout":"%s","variant":"%s","options":"%s","rate":"%s","repeat_rate":%s,"repeat_delay":%s,"badge":"%s"}\n' \
                "$KB_TYPE" "$KB_MODEL" "$KB_LAYOUT" "$KB_VARIANT" "$opts" \
                "$KB_RATE_NAME" "$KB_REPEAT_RATE" "$KB_REPEAT_DELAY" "$badge"
            ;;
        --waybar)
            local tip="Keyboard: ${tlabel}\\nLayout: ${KB_LAYOUT}${KB_VARIANT:+ (${KB_VARIANT})}\\nRepeat: ${KB_REPEAT_RATE} Hz / ${KB_REPEAT_DELAY} ms\\nLeft-click: Switch layout · Right-click: Keyboard Studio"
            printf '{"text":"%s","tooltip":"%s","class":"kb-%s"}\n' "$badge" "$tip" "$KB_TYPE"
            ;;
        *)
            printf 'type=%s layout=%s variant=%s rate=%s(%sHz/%sms) badge=%s\n' \
                "$KB_TYPE" "$KB_LAYOUT" "${KB_VARIANT:-none}" "$KB_RATE_NAME" \
                "$KB_REPEAT_RATE" "$KB_REPEAT_DELAY" "$badge"
            ;;
    esac
}

cmd_menu() {
    have rofi || exit 1
    load_kb_state
    local tab=$'\t' choice key badge
    badge="$(compute_badge)"
    choice="$(printf '%s\n' \
        "type:ansi${tab}Hardware Type  : Standard ANSI 104/87-Key (Mechanical / Desktop)" \
        "type:compact60${tab}Hardware Type  : 60% / HHKB Compact (CapsLock acts as Escape)" \
        "type:vim${tab}Hardware Type  : Vim / Developer Ergonomic (Swap CapsLock & Escape)" \
        "type:emacs${tab}Hardware Type  : Control Home-Row (CapsLock acts as Ctrl)" \
        "type:iso${tab}Hardware Type  : ISO 105-Key (European / UK Split Enter)" \
        "type:apple${tab}Hardware Type  : Apple / Magic Keyboard (Swap Cmd & Alt -> Super)" \
        "type:laptop${tab}Hardware Type  : ThinkPad / Compact Laptop" \
        "layout:qwerty${tab}Keymap Layout  : US QWERTY (Standard)" \
        "layout:colemak-dh${tab}Keymap Layout  : Colemak-DH (Matrix Ergonomic)" \
        "layout:colemak${tab}Keymap Layout  : Colemak Classic" \
        "layout:dvorak${tab}Keymap Layout  : US Dvorak" \
        "layout:workman${tab}Keymap Layout  : Workman" \
        "layout:intl${tab}Keymap Layout  : US International (Accents / AltGr)" \
        "layout:azerty${tab}Keymap Layout  : French AZERTY (fr)" \
        "layout:qwertz${tab}Keymap Layout  : German QWERTZ (de)" \
        "layout:uk${tab}Keymap Layout  : British UK ISO (gb)" \
        "layout:us-ara${tab}Dual Toggle    : US + Arabic (us,ara)" \
        "layout:us-fr${tab}Dual Toggle    : US + French (us,fr)" \
        "layout:us-es${tab}Dual Toggle    : US + Spanish (us,es)" \
        "layout:us-ru${tab}Dual Toggle    : US + Russian (us,ru)" \
        "custom${tab}Custom XKB     : Enter any layout[:variant] (e.g. jp, latam, us,de)..." \
        "rate:tactile${tab}Repeat Feel    : Tactile Balanced (38 Hz / 260 ms)" \
        "rate:rapid${tab}Repeat Feel    : Rapid Modal Navigation (55 Hz / 190 ms)" \
        "rate:gentle${tab}Repeat Feel    : Gentle Prose (25 Hz / 360 ms)" \
        | rofi_menu settings -dmenu -i -display-columns 2 -display-column-separator "$tab" \
            -p "keyboard studio:" \
            -mesg "Active: [${badge}] $(type_label "$KB_TYPE") | ${KB_REPEAT_RATE}Hz/${KB_REPEAT_DELAY}ms")" || exit 0
    [ -n "$choice" ] || exit 0
    key="${choice%%"$tab"*}"
    case "$key" in
        type:*)   cmd_type "${key#type:}" ;;
        layout:*) cmd_layout "${key#layout:}" ;;
        rate:*)   cmd_rate "${key#rate:}" ;;
        custom)
            local custom_spec
            custom_spec="$(printf '' | rofi_menu launcher -dmenu -p "xkb layout[:variant]:")" || exit 0
            [ -n "$custom_spec" ] && cmd_layout "$custom_spec"
            ;;
    esac
}

case "${1:-menu}" in
    status)     cmd_status "${2:-}" ;;
    next|cycle) cmd_next ;;
    type|model) cmd_type "${2:-}" ;;
    layout|set) cmd_layout "${2:-}" ;;
    rate)       cmd_rate "${2:-}" ;;
    menu|"")    cmd_menu ;;
    *)
        echo "usage: keyboard.sh [menu|status|next|type|layout|rate]" >&2
        exit 1 ;;
esac
