namespace fs = std::filesystem;
using mono_cfg::JsonVal;

namespace {

double lua_num(const std::string& user_lua, const std::string& key, double fallback) {
    try {
        return std::stod(mono_cfg::lua_value(user_lua, key, std::to_string(fallback)));
    } catch (...) {
        return fallback;
    }
}

JsonVal build_wt_scheme(const std::map<std::string, std::string>& kitty) {
    auto c = [&](const std::string& k, const std::string& fb) -> std::string {
        auto it = kitty.find(k);
        return (it != kitty.end()) ? it->second : fb;
    };
    return JsonVal(JsonVal::Object{
        {"name", "hyprland-monochrome"},
        {"background", c("background", "#0a0a0a")},
        {"foreground", c("foreground", "#e6e6e6")},
        {"cursorColor", c("cursor", "#e6e6e6")},
        {"selectionBackground", c("selection_background", "#e6e6e6")},
        {"black", c("color0", "#141414")},
        {"red", c("color1", "#141414")},
        {"green", c("color2", "#141414")},
        {"yellow", c("color3", "#141414")},
        {"blue", c("color4", "#141414")},
        {"purple", c("color5", "#141414")},
        {"cyan", c("color6", "#141414")},
        {"white", c("color7", "#141414")},
        {"brightBlack", c("color8", "#ffffff")},
        {"brightRed", c("color9", "#ffffff")},
        {"brightGreen", c("color10", "#ffffff")},
        {"brightYellow", c("color11", "#ffffff")},
        {"brightBlue", c("color12", "#ffffff")},
        {"brightPurple", c("color13", "#ffffff")},
        {"brightCyan", c("color14", "#ffffff")},
        {"brightWhite", c("color15", "#ffffff")},
    });
}

JsonVal build_wt_settings(const std::string& user_lua, const std::map<std::string, std::string>& kitty) {
    int opacity = static_cast<int>(lua_num(user_lua, "terminal_opacity", 0.92) * 100.0);
    return JsonVal(JsonVal::Object{
        {"profiles", JsonVal(JsonVal::Object{
            {"defaults", JsonVal(JsonVal::Object{
                {"colorScheme", "hyprland-monochrome"},
                {"font", JsonVal(JsonVal::Object{
                    {"face", "JetBrainsMono Nerd Font"},
                    {"size", 11},
                })},
                {"opacity", opacity},
                {"padding", "14"},
                {"useAcrylic", true},
                {"cursorShape", "bar"},
                {"antialiasingMode", "cleartype"},
            })},
        })},
        {"schemes", JsonVal::Array{build_wt_scheme(kitty)}},
        {"_comment", "Merge this into %LOCALAPPDATA%\\Packages\\Microsoft.WindowsTerminal_*\\LocalState\\settings.json \xe2\x80\x94 or open Settings with Ctrl+, \xe2\x86\x92 Open JSON file and paste. The scheme comes from .config/kitty/theme.conf, so both terminals are the same greys. 'opacity' and 'padding' come from modules/user.lua."},
    });
}

std::string build_glazewm_yaml(const std::string& user_lua, const std::map<std::string, std::string>& kitty) {
    int inner = static_cast<int>(lua_num(user_lua, "gaps_in", 5.0));
    int outer = static_cast<int>(lua_num(user_lua, "gaps_out", 10.0));
    int rounding = static_cast<int>(lua_num(user_lua, "rounding", 10.0));
    double inactive = lua_num(user_lua, "inactive_opacity", 0.94);
    int count = static_cast<int>(lua_num(user_lua, "workspace_count", 10.0));

    std::string text = kitty.count("foreground") ? kitty.at("foreground") : "#e6e6e6";
    std::string hairline = kitty.count("inactive_border_color") ? kitty.at("inactive_border_color") : "#2a2a2a";
    std::string corner = (rounding >= 8) ? "rounded" : ((rounding >= 4) ? "small_rounded" : "square");
    std::string opacity = std::to_string(static_cast<int>(std::round(inactive * 100.0))) + "%";

    std::ostringstream o;
    o << "# ═══════════════════════════════════════════════════════════════════════════\n"
      << "#  glazewm-config.yaml — the Windows half of hyprland-monochrome\n"
      << "#\n"
      << "#  GENERATED by tools/build-windows-kit.cpp from modules/user.lua and\n"
      << "#  kitty/theme.conf. Edit those and re-run `make docs`; edits here get overwritten.\n"
      << "#\n"
      << "#  Install:  winget install GlazeWM      (Zebar is offered during setup)\n"
      << "#  Place at: %userprofile%\\.glzr\\glazewm\\config.yaml\n"
      << "#\n"
      << "#  Hyprland itself cannot run on Windows (no Wayland, no DRM), so this is the\n"
      << "#  closest thing: GlazeWM is an i3-style tiling WM, and Zebar is a bar in the\n"
      << "#  same spirit as Waybar.\n"
      << "#\n"
      << "#  Note on the modifier: this setup uses SUPER on Linux. Windows reserves some\n"
      << "#  Windows-key combinations (lwin+l, lwin+d …), so GlazeWM's own docs advise\n"
      << "#  against it. Everything below therefore uses ALT. If you want to match Linux\n"
      << "#  exactly, swap the alt+ prefixes for lwin+ and expect a few clashes.\n"
      << "# ═══════════════════════════════════════════════════════════════════════════\n\n"
      << "general:\n"
      << "  # Left empty on purpose: these commands run on every launch, and if Zebar is\n"
      << "  # not installed GlazeWM will pop up an error each time. Uncomment the pair\n"
      << "  # below once you have Zebar running.\n"
      << "  startup_commands: []\n"
      << "  shutdown_commands: []\n"
      << "  # startup_commands: ['shell-exec zebar']\n"
      << "  # shutdown_commands: ['shell-exec taskkill /IM zebar.exe /F']\n"
      << "  focus_follows_cursor: false\n"
      << "  cursor_jump:\n"
      << "    enabled: true\n"
      << "    trigger: 'monitor_focus'\n"
      << "  hide_method: 'cloak'\n"
      << "  show_all_in_taskbar: false\n\n"
      << "# gaps_in / gaps_out from modules/user.lua. The top gap leaves room for Zebar.\n"
      << "gaps:\n"
      << "  scale_with_dpi: true\n"
      << "  inner_gap: '" << inner << "px'\n"
      << "  outer_gap:\n"
      << "    top: '" << (outer + 34) << "px'\n"
      << "    right: '" << outer << "px'\n"
      << "    bottom: '" << outer << "px'\n"
      << "    left: '" << outer << "px'\n\n"
      << "# The monochrome look: a white border on the focused window, near-black on the\n"
      << "# rest, no title bars (Hyprland draws none either).\n"
      << "window_effects:\n"
      << "  focused_window:\n"
      << "    border:\n"
      << "      enabled: true\n"
      << "      color: '" << text << "'\n"
      << "    hide_title_bar:\n"
      << "      enabled: true\n"
      << "    corner_style:\n"
      << "      enabled: true\n"
      << "      style: '" << corner << "'\n"
      << "    transparency:\n"
      << "      enabled: false\n"
      << "      opacity: '100%'\n"
      << "  other_windows:\n"
      << "    border:\n"
      << "      enabled: true\n"
      << "      color: '" << hairline << "'\n"
      << "    hide_title_bar:\n"
      << "      enabled: true\n"
      << "    corner_style:\n"
      << "      enabled: true\n"
      << "      style: '" << corner << "'\n"
      << "    transparency:\n"
      << "      enabled: true\n"
      << "      opacity: '" << opacity << "'        # inactive_opacity from user.lua\n\n"
      << "window_behavior:\n"
      << "  initial_state: 'tiling'\n"
      << "  state_defaults:\n"
      << "    floating:\n"
      << "      centered: true\n"
      << "      shown_on_top: false\n"
      << "    fullscreen:\n"
      << "      maximized: false\n"
      << "      shown_on_top: true\n\n"
      << "workspaces:\n";

    for (int i = 1; i <= count; ++i) {
        o << "  - name: '" << i << "'\n";
    }

    o << "\nwindow_rules:\n"
      << "  - commands: ['ignore']\n"
      << "    match:\n"
      << "      # Zebar is the bar — never tile it (our layer rules do the same for Waybar).\n"
      << "      - window_process: { equals: 'zebar' }\n"
      << "      - window_process: { equals: 'Zebar' }\n"
      << "      # Picture-in-picture stays floating, like the rule in Hyprland.\n"
      << "      - window_title: { regex: '[Pp]icture.in.[Pp]icture' }\n"
      << "        window_class: { regex: 'Chrome_WidgetWin_1|MozillaDialogClass' }\n"
      << "      # PowerToys widgets are overlays, not windows.\n"
      << "      - window_process: { equals: 'PowerToys' }\n"
      << "        window_class: { regex: 'HwndWrapper\\[PowerToys\\.PowerAccent.*?\\]' }\n"
      << "      - window_title: { equals: 'Command Palette' }\n"
      << "        window_class: { equals: 'WinUIDesktopWin32WindowClass' }\n\n"
      << "binding_modes:\n"
      << "  # alt+r, then HJKL / arrows — same idea as the resize keybinds in binds.lua.\n"
      << "  - name: 'resize'\n"
      << "    keybindings:\n"
      << "      - commands: ['resize --width -2%']\n"
      << "        bindings: ['h', 'left']\n"
      << "      - commands: ['resize --width +2%']\n"
      << "        bindings: ['l', 'right']\n"
      << "      - commands: ['resize --height +2%']\n"
      << "        bindings: ['k', 'up']\n"
      << "      - commands: ['resize --height -2%']\n"
      << "        bindings: ['j', 'down']\n"
      << "      - commands: ['wm-disable-binding-mode --name resize']\n"
      << "        bindings: ['escape', 'enter', 'alt+r']\n\n"
      << "keybindings:\n"
      << "  # ── Launching (the shell-exec equivalents of our Rofi bindings) ──────────\n"
      << "  - commands: ['shell-exec wt']                      # alt+enter / alt+t → terminal\n"
      << "    bindings: ['alt+enter']\n"
      << "  - commands: ['shell-exec explorer']                # alt+e → file manager\n"
      << "    bindings: ['alt+e']\n"
      << "  - commands: ['shell-exec cmd /c start \"\" https://']  # alt+b → browser\n"
      << "    bindings: ['alt+b']\n"
      << "  - commands: ['shell-exec ms-screenclip:']          # alt+print → screenshot\n"
      << "    bindings: ['alt+print_screen']\n"
      << "  - commands: ['shell-exec wt -p \"Command Prompt\"']  # only if you want a second shell\n"
      << "    bindings: ['alt+shift+t']\n\n"
      << "  # ── Focus ────────────────────────────────────────────────────────────────\n"
      << "  - commands: ['focus --direction left']\n"
      << "    bindings: ['alt+h', 'alt+left']\n"
      << "  - commands: ['focus --direction right']\n"
      << "    bindings: ['alt+l', 'alt+right']\n"
      << "  - commands: ['focus --direction up']\n"
      << "    bindings: ['alt+k', 'alt+up']\n"
      << "  - commands: ['focus --direction down']\n"
      << "    bindings: ['alt+j', 'alt+down']\n\n"
      << "  # ── Move the focused window ──────────────────────────────────────────────\n"
      << "  - commands: ['move --direction left']\n"
      << "    bindings: ['alt+shift+h', 'alt+shift+left']\n"
      << "  - commands: ['move --direction right']\n"
      << "    bindings: ['alt+shift+l', 'alt+shift+right']\n"
      << "  - commands: ['move --direction up']\n"
      << "    bindings: ['alt+shift+k', 'alt+shift+up']\n"
      << "  - commands: ['move --direction down']\n"
      << "    bindings: ['alt+shift+j', 'alt+shift+down']\n\n"
      << "  # ── Resize ───────────────────────────────────────────────────────────────\n"
      << "  - commands: ['resize --width -2%']\n"
      << "    bindings: ['alt+u']\n"
      << "  - commands: ['resize --width +2%']\n"
      << "    bindings: ['alt+p']\n"
      << "  - commands: ['resize --height +2%']\n"
      << "    bindings: ['alt+o']\n"
      << "  - commands: ['resize --height -2%']\n"
      << "    bindings: ['alt+i']\n"
      << "  - commands: ['wm-enable-binding-mode --name resize']\n"
      << "    bindings: ['alt+r']\n\n"
      << "  # ── Window state (Super+Space float, Super+F fullscreen on Linux) ────────\n"
      << "  - commands: ['toggle-floating --centered']\n"
      << "    bindings: ['alt+space']\n"
      << "  - commands: ['toggle-tiling']\n"
      << "    bindings: ['alt+shift+space']\n"
      << "  - commands: ['toggle-fullscreen']\n"
      << "    bindings: ['alt+f']\n"
      << "  - commands: ['toggle-minimized']\n"
      << "    bindings: ['alt+m']\n"
      << "  - commands: ['toggle-tiling-direction']\n"
      << "    bindings: ['alt+y']\n"
      << "  - commands: ['wm-cycle-focus']\n"
      << "    bindings: ['alt+tab']\n\n"
      << "  # ── Windows ──────────────────────────────────────────────────────────────\n"
      << "  - commands: ['close']\n"
      << "    bindings: ['alt+q']\n"
      << "  - commands: ['wm-reload-config']\n"
      << "    bindings: ['alt+shift+r']\n"
      << "  - commands: ['wm-redraw']\n"
      << "    bindings: ['alt+shift+w']\n"
      << "  - commands: ['wm-toggle-pause']\n"
      << "    bindings: ['alt+shift+p']\n"
      << "  - commands: ['wm-exit']\n"
      << "    bindings: ['alt+shift+e']\n\n"
      << "  # ── Workspaces (alt+0 is the tenth) ──────────────────────────────────────\n";

    for (int i = 1; i <= count; ++i) {
        std::string key = (i == 10) ? "0" : std::to_string(i);
        o << "  - commands: ['focus --workspace " << i << "']\n"
          << "    bindings: ['alt+" << key << "']\n";
    }
    o << "\n";
    for (int i = 1; i <= count; ++i) {
        std::string key = (i == 10) ? "0" : std::to_string(i);
        o << "  - commands: ['move --workspace " << i << "', 'focus --workspace " << i << "']\n"
          << "    bindings: ['alt+shift+" << key << "']\n";
    }

    o << "\n  # ── Workspaces on other monitors ─────────────────────────────────────────\n"
      << "  - commands: ['move-workspace --direction left']\n"
      << "    bindings: ['alt+shift+a']\n"
      << "  - commands: ['move-workspace --direction right']\n"
      << "    bindings: ['alt+shift+d']\n";
    return o.str();
}

}  // namespace

int main(int argc, char* argv[]) {
    bool check_only = false;
    for (int i = 1; i < argc; ++i) {
        if (std::string(argv[i]) == "--check") check_only = true;
    }

    fs::path repo = mono_cfg::find_repo_root(argv[0]);
    auto kitty = mono_cfg::parse_kitty_palette(mono_cfg::read_text(repo / ".config/kitty/theme.conf"));
    std::string user_lua = mono_cfg::read_text(repo / ".config/hypr/modules/user.lua");

    fs::path win_dir = repo / "windows";
    std::vector<std::pair<fs::path, std::string>> targets = {
        {win_dir / "glazewm-config.yaml", build_glazewm_yaml(user_lua, kitty)},
        {win_dir / "windows-terminal-scheme.json", mono_cfg::json_dump(build_wt_scheme(kitty), 2) + "\n"},
        {win_dir / "windows-terminal-settings.json", mono_cfg::json_dump(build_wt_settings(user_lua, kitty), 2) + "\n"},
    };

    if (check_only) {
        std::vector<std::string> stale;
        for (const auto& [path, content] : targets) {
            if (!fs::exists(path) || mono_cfg::read_text(path) != content) {
                stale.push_back(fs::relative(path, repo).string());
            }
        }
        if (!stale.empty()) {
            std::cerr << "stale: " << stale.front() << "\n";
            std::cerr << "run: make docs (./bin/build-windows-kit)\n";
            return 1;
        }
        std::cout << "windows kit is up to date.\n";
        return 0;
    }

    fs::create_directories(win_dir);
    for (const auto& [path, content] : targets) {
        mono_cfg::write_text(path, content);
    }
    std::cout << "wrote " << targets.size() << " files in windows/\n";
    return 0;
}
