#!/usr/bin/env python3
"""
tools/build-windows-kit.py — the Windows half of this setup.

Hyprland is a Linux-only Wayland compositor: it cannot run on Windows, and not
under WSL2 either (no DRM/GPU access). What *can* move over is everything that
makes this desktop feel like itself — the greyscale palette, the gaps, the
keybind layout and the tiling workflow.

So this generates a small kit in windows/, built from the same source of truth
the Linux side uses (modules/user.lua and kitty/theme.conf):

    windows/glazewm-config.yaml              → GlazeWM, the i3-style tiler for Windows
    windows/windows-terminal-scheme.json     → the mono palette as a Windows Terminal scheme
    windows/windows-terminal-settings.json   → the snippet that applies it

    python3 tools/build-windows-kit.py           # (re)generate
    python3 tools/build-windows-kit.py --check   # exit 1 if the kit is stale

Nothing here is invented: every value is read from the repo.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CONFIG = REPO / ".config"
OUT = REPO / "windows"
USER_LUA = CONFIG / "hypr" / "modules" / "user.lua"
KITTY = CONFIG / "kitty" / "theme.conf"


# ── reading the repository ────────────────────────────────────────────────

def mono_var(name: str, fallback: str = "") -> str:
    """Same value the shell scripts read (keep in step with scripts/lib.sh)."""
    text = USER_LUA.read_text()
    match = re.search(rf"^[ \t]*{re.escape(name)}[ \t]*=[ \t]*(.+)$", text, re.M)
    if not match:
        return fallback
    value = re.split(r"\s+--", match.group(1), maxsplit=1)[0].strip().rstrip(",").strip()
    value = re.sub(r'^home\s*\.\.\s*', "$HOME/", value)
    return value.strip().strip('"').strip("'")


def mono_num(name: str, fallback: float) -> float:
    try:
        return float(mono_var(name, str(fallback)))
    except ValueError:
        return fallback


def mono_bool(name: str, fallback: bool) -> bool:
    value = mono_var(name, "true" if fallback else "false").lower()
    return value not in ("false", "0", "no")


def kitty_palette() -> dict[str, str]:
    """background/foreground/cursor/color0..15 out of kitty/theme.conf."""
    palette: dict[str, str] = {}
    for line in KITTY.read_text().splitlines():
        line = line.split("#")[0].strip() if not line.strip().startswith("#") else ""
        if not line:
            continue
        parts = line.split()
        if len(parts) >= 2 and parts[1].startswith("#"):
            palette[parts[0]] = parts[1]
    return palette


# ── GlazeWM ───────────────────────────────────────────────────────────────

def glazewm_config() -> str:
    inner = int(mono_num("gaps_in", 5))
    outer = int(mono_num("gaps_out", 10))
    rounding = int(mono_num("rounding", 10))
    inactive = mono_num("inactive_opacity", 0.94)
    blur = mono_bool("blur_enabled", True)
    count = int(mono_num("workspace_count", 10))
    kitty = kitty_palette()

    text = kitty.get("foreground", "#e6e6e6")
    dim = kitty.get("color8", "#4a4a4a")            # the greyscale ramp's dark grey
    hairline = kitty.get("inactive_border_color", "#2a2a2a")
    surface = kitty.get("background", "#0a0a0a")
    corner = "rounded" if rounding >= 8 else ("small_rounded" if rounding >= 4 else "square")
    opacity = f"{int(round(inactive * 100))}%"

    workspaces = "\n".join(f"  - name: '{i}'" for i in range(1, count + 1))

    # mod+1..0 mirrors the Linux setup: the tenth workspace lives on the 0 key.
    focus_ws = []
    move_ws = []
    for i in range(1, count + 1):
        key = "0" if i == 10 else str(i)
        focus_ws.append(f"  - commands: ['focus --workspace {i}']\n    bindings: ['alt+{key}']")
        move_ws.append(
            f"  - commands: ['move --workspace {i}', 'focus --workspace {i}']\n"
            f"    bindings: ['alt+shift+{key}']"
        )

    return f"""# ═══════════════════════════════════════════════════════════════════════════
#  glazewm-config.yaml — the Windows half of hyprland-monochrome
#
#  GENERATED by tools/build-windows-kit.py from modules/user.lua and
#  kitty/theme.conf. Edit those and re-run the tool; edits here get overwritten.
#
#  Install:  winget install GlazeWM      (Zebar is offered during setup)
#  Place at: %userprofile%\\.glzr\\glazewm\\config.yaml
#
#  Hyprland itself cannot run on Windows (no Wayland, no DRM), so this is the
#  closest thing: GlazeWM is an i3-style tiling WM, and Zebar is a bar in the
#  same spirit as Waybar.
#
#  Note on the modifier: this setup uses SUPER on Linux. Windows reserves some
#  Windows-key combinations (lwin+l, lwin+d …), so GlazeWM's own docs advise
#  against it. Everything below therefore uses ALT. If you want to match Linux
#  exactly, swap the alt+ prefixes for lwin+ and expect a few clashes.
# ═══════════════════════════════════════════════════════════════════════════

general:
  # Left empty on purpose: these commands run on every launch, and if Zebar is
  # not installed GlazeWM will pop up an error each time. Uncomment the pair
  # below once you have Zebar running.
  startup_commands: []
  shutdown_commands: []
  # startup_commands: ['shell-exec zebar']
  # shutdown_commands: ['shell-exec taskkill /IM zebar.exe /F']
  focus_follows_cursor: false
  cursor_jump:
    enabled: true
    trigger: 'monitor_focus'
  hide_method: 'cloak'
  show_all_in_taskbar: false

# gaps_in / gaps_out from modules/user.lua. The top gap leaves room for Zebar.
gaps:
  scale_with_dpi: true
  inner_gap: '{inner}px'
  outer_gap:
    top: '{outer + 34}px'
    right: '{outer}px'
    bottom: '{outer}px'
    left: '{outer}px'

# The monochrome look: a white border on the focused window, near-black on the
# rest, no title bars (Hyprland draws none either).
window_effects:
  focused_window:
    border:
      enabled: true
      color: '{text}'
    hide_title_bar:
      enabled: true
    corner_style:
      enabled: true
      style: '{corner}'
    transparency:
      enabled: false
      opacity: '100%'
  other_windows:
    border:
      enabled: true
      color: '{hairline}'
    hide_title_bar:
      enabled: true
    corner_style:
      enabled: true
      style: '{corner}'
    transparency:
      enabled: true
      opacity: '{opacity}'        # inactive_opacity from user.lua

window_behavior:
  initial_state: 'tiling'
  state_defaults:
    floating:
      centered: true
      shown_on_top: false
    fullscreen:
      maximized: false
      shown_on_top: true

workspaces:
{workspaces}

window_rules:
  - commands: ['ignore']
    match:
      # Zebar is the bar — never tile it (our layer rules do the same for Waybar).
      - window_process: {{ equals: 'zebar' }}
      - window_process: {{ equals: 'Zebar' }}
      # Picture-in-picture stays floating, like the rule in Hyprland.
      - window_title: {{ regex: '[Pp]icture.in.[Pp]icture' }}
        window_class: {{ regex: 'Chrome_WidgetWin_1|MozillaDialogClass' }}
      # PowerToys widgets are overlays, not windows.
      - window_process: {{ equals: 'PowerToys' }}
        window_class: {{ regex: 'HwndWrapper\\[PowerToys\\.PowerAccent.*?\\]' }}
      - window_title: {{ equals: 'Command Palette' }}
        window_class: {{ equals: 'WinUIDesktopWin32WindowClass' }}

binding_modes:
  # alt+r, then HJKL / arrows — same idea as the resize keybinds in binds.lua.
  - name: 'resize'
    keybindings:
      - commands: ['resize --width -2%']
        bindings: ['h', 'left']
      - commands: ['resize --width +2%']
        bindings: ['l', 'right']
      - commands: ['resize --height +2%']
        bindings: ['k', 'up']
      - commands: ['resize --height -2%']
        bindings: ['j', 'down']
      - commands: ['wm-disable-binding-mode --name resize']
        bindings: ['escape', 'enter', 'alt+r']

keybindings:
  # ── Launching (the shell-exec equivalents of our Rofi bindings) ──────────
  - commands: ['shell-exec wt']                      # alt+enter / alt+t → terminal
    bindings: ['alt+enter']
  - commands: ['shell-exec explorer']                # alt+e → file manager
    bindings: ['alt+e']
  - commands: ['shell-exec cmd /c start "" https://']  # alt+b → browser
    bindings: ['alt+b']
  - commands: ['shell-exec ms-screenclip:']          # alt+print → screenshot
    bindings: ['alt+print_screen']
  - commands: ['shell-exec wt -p "Command Prompt"']  # only if you want a second shell
    bindings: ['alt+shift+t']

  # ── Focus ────────────────────────────────────────────────────────────────
  - commands: ['focus --direction left']
    bindings: ['alt+h', 'alt+left']
  - commands: ['focus --direction right']
    bindings: ['alt+l', 'alt+right']
  - commands: ['focus --direction up']
    bindings: ['alt+k', 'alt+up']
  - commands: ['focus --direction down']
    bindings: ['alt+j', 'alt+down']

  # ── Move the focused window ──────────────────────────────────────────────
  - commands: ['move --direction left']
    bindings: ['alt+shift+h', 'alt+shift+left']
  - commands: ['move --direction right']
    bindings: ['alt+shift+l', 'alt+shift+right']
  - commands: ['move --direction up']
    bindings: ['alt+shift+k', 'alt+shift+up']
  - commands: ['move --direction down']
    bindings: ['alt+shift+j', 'alt+shift+down']

  # ── Resize ───────────────────────────────────────────────────────────────
  - commands: ['resize --width -2%']
    bindings: ['alt+u']
  - commands: ['resize --width +2%']
    bindings: ['alt+p']
  - commands: ['resize --height +2%']
    bindings: ['alt+o']
  - commands: ['resize --height -2%']
    bindings: ['alt+i']
  - commands: ['wm-enable-binding-mode --name resize']
    bindings: ['alt+r']

  # ── Window state (Super+Space float, Super+F fullscreen on Linux) ────────
  - commands: ['toggle-floating --centered']
    bindings: ['alt+space']
  - commands: ['toggle-tiling']
    bindings: ['alt+shift+space']
  - commands: ['toggle-fullscreen']
    bindings: ['alt+f']
  - commands: ['toggle-minimized']
    bindings: ['alt+m']
  - commands: ['toggle-tiling-direction']
    bindings: ['alt+y']
  - commands: ['wm-cycle-focus']
    bindings: ['alt+tab']

  # ── Windows ──────────────────────────────────────────────────────────────
  - commands: ['close']
    bindings: ['alt+q']
  - commands: ['wm-reload-config']
    bindings: ['alt+shift+r']
  - commands: ['wm-redraw']
    bindings: ['alt+shift+w']
  - commands: ['wm-toggle-pause']
    bindings: ['alt+shift+p']
  - commands: ['wm-exit']
    bindings: ['alt+shift+e']

  # ── Workspaces (alt+0 is the tenth) ──────────────────────────────────────
{chr(10).join(focus_ws)}

{chr(10).join(move_ws)}

  # ── Workspaces on other monitors ─────────────────────────────────────────
  - commands: ['move-workspace --direction left']
    bindings: ['alt+shift+a']
  - commands: ['move-workspace --direction right']
    bindings: ['alt+shift+d']
"""


# ── Windows Terminal ──────────────────────────────────────────────────────

def wt_scheme() -> dict:
    kitty = kitty_palette()
    names = ["black", "red", "green", "yellow", "blue", "purple", "cyan", "white"]
    scheme = {
        "name": "hyprland-monochrome",
        "background": kitty.get("background", "#0a0a0a"),
        "foreground": kitty.get("foreground", "#e6e6e6"),
        "cursorColor": kitty.get("cursor", "#e6e6e6"),
        "selectionBackground": kitty.get("selection_background", "#e6e6e6"),
    }
    for i, name in enumerate(names):
        scheme[name] = kitty.get(f"color{i}", "#141414")
    for i, name in enumerate(names):
        scheme[f"bright{name[0].upper()}{name[1:]}"] = kitty.get(f"color{i + 8}", "#ffffff")
    return scheme


def wt_settings() -> dict:
    kitty = kitty_palette()
    opacity = int(mono_num("terminal_opacity", 0.92) * 100)
    return {
        "profiles": {
            "defaults": {
                "colorScheme": "hyprland-monochrome",
                "font": {"face": "JetBrainsMono Nerd Font", "size": 11},
                "opacity": opacity,
                "padding": "14",
                "useAcrylic": True,
                # matches the kitty padding/cursor look closely enough
                "cursorShape": "bar",
                "antialiasingMode": "cleartype",
            }
        },
        "schemes": [wt_scheme()],
        "_comment": (
            "Merge this into %LOCALAPPDATA%\\Packages\\Microsoft.WindowsTerminal_*\\"
            "LocalState\\settings.json — or open Settings with Ctrl+, → Open JSON file and "
            "paste. The scheme comes from .config/kitty/theme.conf, so both terminals are "
            "the same greys. 'opacity' and 'padding' come from modules/user.lua."
        ),
    }


# ── writing ───────────────────────────────────────────────────────────────

def build() -> dict[Path, str]:
    return {
        OUT / "glazewm-config.yaml": glazewm_config(),
        OUT / "windows-terminal-scheme.json": json.dumps(wt_scheme(), indent=2) + "\n",
        OUT / "windows-terminal-settings.json": json.dumps(wt_settings(), indent=2) + "\n",
    }


def main() -> int:
    files = build()
    if "--check" in sys.argv:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
        if stale:
            print("stale:", ", ".join(str(p.relative_to(REPO)) for p in stale), file=sys.stderr)
            print("run: python3 tools/build-windows-kit.py", file=sys.stderr)
            return 1
        print("windows kit is up to date.")
        return 0

    OUT.mkdir(exist_ok=True)
    for path, text in files.items():
        path.write_text(text)
    print(f"wrote {len(files)} files in {OUT.relative_to(REPO)}/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
